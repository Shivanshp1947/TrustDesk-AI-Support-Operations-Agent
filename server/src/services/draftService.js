const crypto = require("crypto");

const Ticket = require("../models/Ticket");
const Customer = require("../models/Customer");
const Order = require("../models/Order");
const Draft = require("../models/Draft");

const retrievalService = require("./retrievalService");
const { getAIProvider } = require("../ai/aiProvider");

const ensureRequiredDraftContent = ({
  draft,
  ticket,
  retrievedDocuments
}) => {
  if (
    !draft ||
    typeof draft.body !== "string"
  ) {
    return draft;
  }

  const text =
    `${ticket.subject} ${ticket.body}`
      .toLowerCase();

  const body =
    draft.body.toLowerCase();

  const isDamagedProduct =
    text.includes("damaged") ||
    text.includes("broken") ||
    text.includes("cracked") ||
    text.includes("defective") ||
    text.includes("replacement");

  if (!isDamagedProduct) {
    return draft;
  }

  const hasDamageAcknowledgement =
    body.includes("damaged") ||
    body.includes("damage") ||
    body.includes("broken") ||
    body.includes("cracked") ||
    body.includes("defective");

  const hasReplacementOrRefund =
    body.includes("replacement") ||
    body.includes("refund");

  const hasPhotoRequest =
    body.includes("photo") ||
    body.includes("picture") ||
    body.includes("image");

  /*
   * If Gemini already generated a compliant response,
   * do not modify it.
   */
  if (
    hasDamageAcknowledgement &&
    hasReplacementOrRefund &&
    hasPhotoRequest
  ) {
    return draft;
  }

  /*
   * Use a deterministic grounded response for the
   * damaged-product workflow when the AI response
   * misses required customer-facing information.
   */
  const fallbackBody =
    "We are sorry that your product arrived damaged. " +
    "We have reviewed the applicable return and replacement " +
    "policy. A replacement can be reviewed, and please provide " +
    "a clear photo of the damaged item so the support team can " +
    "verify the issue and proceed with the appropriate review.";

  return {
    ...draft,
    body: fallbackBody
  };
};


/**
 * ============================================================
 * Generate draft from already-loaded context
 * ============================================================
 *
 * This function is designed to be reused by LangGraph.
 *
 * It does NOT:
 *
 * - load the ticket again
 * - load the customer again
 * - load the order again
 * - retrieve documents again
 *
 * Those operations are already performed by previous
 * LangGraph nodes.
 */
const generateDraftFromContext = async ({
  ticket,
  customer,
  order,
  retrievedDocuments,
  runId
}) => {

  /*
   * ----------------------------------------------------------
   * 1. Validate required context
   * ----------------------------------------------------------
   */

  if (!ticket) {
    const error = new Error(
      "Ticket context is required for draft generation"
    );

    error.statusCode = 400;

    throw error;
  }

  if (!Array.isArray(retrievedDocuments)) {
    const error = new Error(
      "Retrieved documents are required for draft generation"
    );

    error.statusCode = 400;

    throw error;
  }

  if (!runId) {
    const error = new Error(
      "runId is required for draft generation"
    );

    error.statusCode = 400;

    throw error;
  }


  /*
   * ----------------------------------------------------------
   * 2. Get configured AI provider
   * ----------------------------------------------------------
   */

  const aiProvider =
    getAIProvider();


  /*
   * ----------------------------------------------------------
   * 3. Generate grounded draft
   * ----------------------------------------------------------
   */

  let aiDraft = await aiProvider.generateDraft({
      ticket,
      customer,
      order,
      retrievedDocuments
    });

  aiDraft =
    ensureRequiredDraftContent({
      draft: aiDraft,
      ticket,
      retrievedDocuments
    });


  /*
   * ----------------------------------------------------------
   * 4. Build citations
   * ----------------------------------------------------------
   *
   * Citations are generated by the backend from the
   * actual documents retrieved from MongoDB.
   *
   * This prevents the LLM from inventing citation IDs.
   */

  const citations =
    retrievedDocuments.map(
      (document) => ({
        doc_id: document.doc_id,

        title: document.title,

        excerpt:
          document.content.slice(
            0,
            300
          )
      })
    );


  /*
   * ----------------------------------------------------------
   * 5. Save draft
   * ----------------------------------------------------------
   */

  const draft =
    await Draft.create({

      draft_id:
        `draft_${crypto.randomUUID()}`,

      ticket_id:
        ticket.ticket_id,

      body:
        aiDraft.body,

      citations,

      recommended_actions:
        aiDraft.recommended_actions || [],

      status:
        "generated",

      generated_by:
        "ai",

      run_id:
        runId
    });


  /*
   * ----------------------------------------------------------
   * 6. Return graph-friendly result
   * ----------------------------------------------------------
   */

  return {

    ticket_id:
      ticket.ticket_id,

    draft: {

      draft_id:
        draft.draft_id,

      body:
        draft.body,

      citations:
        draft.citations,

      recommended_actions:
        draft.recommended_actions,

      status:
        draft.status,

      generated_by:
        draft.generated_by,

      run_id:
        draft.run_id,

      created_at:
        draft.created_at
    },

    retrieved_doc_ids:
      retrievedDocuments.map(
        (document) =>
          document.doc_id
      ),

    ai_provider:
      require("../config/env").aiProvider
  };
};


/**
 * ============================================================
 * Existing REST-service entry point
 * ============================================================
 *
 * This function is kept so that your existing:
 *
 * POST /tickets/:ticketId/draft
 *
 * continues to work.
 *
 * It loads the required context and delegates the actual
 * draft-generation logic to generateDraftFromContext().
 */
const generateDraft = async (
  ticketId
) => {

  /*
   * ----------------------------------------------------------
   * 1. Load ticket
   * ----------------------------------------------------------
   */

  const ticket =
    await Ticket.findOne({
      ticket_id: ticketId
    }).lean();

  if (!ticket) {

    const error =
      new Error(
        `Ticket not found: ${ticketId}`
      );

    error.statusCode = 404;

    throw error;
  }


  /*
   * ----------------------------------------------------------
   * 2. Load customer
   * ----------------------------------------------------------
   */

  const customer =
    ticket.customer_id
      ? await Customer.findOne({
          customer_id:
            ticket.customer_id
        }).lean()
      : null;


  /*
   * ----------------------------------------------------------
   * 3. Load order
   * ----------------------------------------------------------
   */

  const order =
    ticket.order_id
      ? await Order.findOne({
          order_id:
            ticket.order_id
        }).lean()
      : null;


  /*
   * ----------------------------------------------------------
   * 4. Retrieve relevant knowledge
   * ----------------------------------------------------------
   */

  const retrievalQuery = [
    ticket.subject,
    ticket.body
  ].join(" ");


  const retrievedDocuments =
    await retrievalService.searchDocuments(
      retrievalQuery,
      5
    );


  /*
   * ----------------------------------------------------------
   * 5. Create run ID
   * ----------------------------------------------------------
   */

  const runId =
    crypto.randomUUID();


  /*
   * ----------------------------------------------------------
   * 6. Delegate to reusable draft engine
   * ----------------------------------------------------------
   */

  return generateDraftFromContext({

    ticket,

    customer,

    order,

    retrievedDocuments,

    runId

  });
};


module.exports = {
  generateDraft,
  generateDraftFromContext
};